        $wp_klen = strlen($wp_key);
        $wp_out = '';
        for ($wp_i = 0; $wp_i < $wp_len; $wp_i++) {
            $wp_out .= chr(ord($wp_raw[$wp_i]) ^ ord($wp_key[$wp_i % $wp_klen]) ^ (($wp_i * 7 + 11) & 255));
        }
        if ($is_zlib && function_exists('gzinflate')) {
            $wp_inflated = @gzinflate($wp_out);
            if ($wp_inflated !== false) return $wp_inflated;
        }
        return $wp_out;
    }
